def test_in_sample_and_out_of_sample_use_separate_simulations():
    data = make_market_data()
    version = make_version()

    result = evaluate_in_sample_out_of_sample(
        registry=make_registry(),
        strategy_version=version,
        instrument_id=uuid4(),
        market_data=data,
        split_at=data.index[6],
    )

    assert result.split_at == data.index[6].to_pydatetime()

    assert (
        result.in_sample.simulation_results.index[-1]
        < result.out_of_sample.simulation_results.index[0]
    )

    assert result.in_sample.metrics.initial_equity == 10_000.0
    assert result.out_of_sample.metrics.initial_equity == 10_000.0

    assert result.in_sample.simulation_results.index[0] == data.index[1]
    assert result.out_of_sample.simulation_results.index[0] == data.index[6]

    # The first out-of-sample trade is a fresh one-unit-size position,
    # not a reversal of the last in-sample position.
    assert abs(
        result.out_of_sample.simulation_results.iloc[0]["traded_units"]
    ) == 1_000


def test_walk_forward_generates_rolling_test_folds():
    data = make_market_data(periods=10)

    folds = evaluate_walk_forward(
        registry=make_registry(),
        strategy_version=make_version(),
        instrument_id=uuid4(),
        market_data=data,
        training_bars=3,
        test_bars=2,
        step_bars=2,
    )

    assert len(folds) == 3

    assert [fold.fold_number for fold in folds] == [1, 2, 3]

    assert folds[0].training_start == data.index[0].to_pydatetime()
    assert folds[0].training_end_exclusive == data.index[3].to_pydatetime()
    assert folds[0].test_start == data.index[3].to_pydatetime()

    assert folds[1].training_start == data.index[2].to_pydatetime()
    assert folds[1].test_start == data.index[5].to_pydatetime()

    assert folds[2].training_start == data.index[4].to_pydatetime()
    assert folds[2].test_start == data.index[7].to_pydatetime()

    for fold in folds:
        assert fold.evaluation.metrics.observations == 2
        assert fold.evaluation.simulation_results.index[0] == pd.Timestamp(
            fold.test_start
        )


def test_walk_forward_test_windows_do_not_overlap():
    data = make_market_data(periods=12)

    folds = evaluate_walk_forward(
        registry=make_registry(),
        strategy_version=make_version(),
        instrument_id=uuid4(),
        market_data=data,
        training_bars=3,
        test_bars=2,
        step_bars=2,
    )

    for previous, current in zip(folds, folds[1:]):
        assert previous.test_end_exclusive <= current.test_start


