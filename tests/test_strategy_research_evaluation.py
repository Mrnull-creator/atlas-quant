def test_evaluation_rejects_fractional_exposure():
    class FractionalImplementation:
        implementation_key = "fractional"
        implementation_version = "1.0.0"

        def validate_parameters(self, parameters):
            return parameters

        def generate_signals(
            self,
            *,
            instrument_id,
            strategy_version,
            market_data,
        ):
            return (
                StrategySignal(
                    strategy_version_id=strategy_version.strategy_version_id,
                    instrument_id=instrument_id,
                    generated_at=market_data.index[1].to_pydatetime()
                    + timedelta(minutes=1),
                    effective_at=market_data.index[2].to_pydatetime(),
                    target_exposure=Decimal("0.5"),
                ),
            )

    registry = InMemoryStrategyImplementationRegistry()
    registry.register(FractionalImplementation())

    data = make_market_data()
    version = make_version(
        implementation_key="fractional",
        implementation_version="1.0.0",
    )

    with pytest.raises(ValueError, match="only -1, 0, and 1"):
        evaluate_strategy(
            registry=registry,
            strategy_version=version,
            instrument_id=uuid4(),
            market_data=data,
            start=data.index[4],
            end_exclusive=data.index[8],
        )
