def test_evaluation_fingerprint_is_reproducible():
    registry = make_registry()
    version = make_version()
    instrument_id = uuid4()
    data = make_market_data()

    first = evaluate_strategy(
        registry=registry,
        strategy_version=version,
        instrument_id=instrument_id,
        market_data=data,
        start=data.index[4],
        end_exclusive=data.index[8],
    )

    second = evaluate_strategy(
        registry=registry,
        strategy_version=version,
        instrument_id=instrument_id,
        market_data=data.copy(),
        start=data.index[4],
        end_exclusive=data.index[8],
    )

    assert first.data_fingerprint == second.data_fingerprint
    assert len(first.data_fingerprint) == 64


def test_future_observations_do_not_change_evaluation_fingerprint_or_results():
    registry = make_registry()
    version = make_version()
    instrument_id = uuid4()
    data = make_market_data()

    changed_future = data.copy()
    changed_future.loc[data.index[8]:, "bid_close"] += 0.5
    changed_future.loc[data.index[8]:, "ask_close"] += 0.5

    original_result = evaluate_strategy(
        registry=registry,
        strategy_version=version,
        instrument_id=instrument_id,
        market_data=data,
        start=data.index[4],
        end_exclusive=data.index[8],
    )

    changed_result = evaluate_strategy(
        registry=make_registry(),
        strategy_version=version,
        instrument_id=instrument_id,
        market_data=changed_future,
        start=data.index[4],
        end_exclusive=data.index[8],
    )

    assert original_result.data_fingerprint == changed_result.data_fingerprint
    pd.testing.assert_frame_equal(
        original_result.simulation_results,
        changed_result.simulation_results,
    )


