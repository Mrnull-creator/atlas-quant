UTC = timezone.utc
START = pd.Timestamp("2026-01-01T00:00:00Z")


def make_version(
    parameters=None,
    implementation_key="momentum",
    implementation_version="1.0.0",
):
    strategy = Strategy(
        name="Momentum",
        strategy_key="momentum",
    )

    import json

    return StrategyVersion(
        strategy_id=strategy.strategy_id,
        version_number=1,
        implementation_key=implementation_key,
        implementation_version=implementation_version,
        parameters_json=json.dumps(
            parameters or {"fast_period": 2, "slow_period": 3}
        ),
    )


def make_market_data(prices=None, periods=10):
    if prices is None:
        base_prices = [1.0, 2.0, 3.0, 4.0, 3.0, 2.0, 1.0, 2.0, 3.0, 4.0]
        prices = [
            base_prices[index % len(base_prices)]
            for index in range(periods)
        ]

    assert len(prices) == periods

    opens = pd.date_range(START, periods=periods, freq="min")
    closes = opens + pd.Timedelta(minutes=1)

    midpoint = pd.Series(prices, index=opens, dtype="float64")

    return pd.DataFrame(
        {
            "bid_open": midpoint - 0.0001,
            "ask_open": midpoint + 0.0001,
            "bid_close": midpoint - 0.0001,
            "ask_close": midpoint + 0.0001,
            "bar_close_time": closes,
        },
        index=opens,
    )


def make_registry():
    registry = InMemoryStrategyImplementationRegistry()
    registry.register(MomentumStrategyImplementation())
    return registry


def test_evaluation_uses_exact_registered_strategy_version():
    registry = make_registry()
    version = make_version()
    instrument_id = uuid4()
    data = make_market_data()

    result = evaluate_strategy(
        registry=registry,
        strategy_version=version,
        instrument_id=instrument_id,
        market_data=data,
        start=data.index[4],
        end_exclusive=data.index[8],
    )

    assert result.strategy_id == version.strategy_id
    assert result.strategy_version_id == version.strategy_version_id
    assert result.version_number == 1
    assert result.implementation_key == "momentum"
    assert result.implementation_version == "1.0.0"


def test_evaluation_executes_previous_completed_bar_signal_at_first_test_open():
    registry = make_registry()
    version = make_version()
    instrument_id = uuid4()
    data = make_market_data()

    result = evaluate_strategy(
        registry=registry,
        strategy_version=version,
        instrument_id=instrument_id,
        market_data=data,
        start=data.index[4],
        end_exclusive=data.index[8],
    )

    first_row = result.simulation_results.iloc[0]

    # The signal generated by bar 3 becomes effective at bar 4's open.
    assert result.simulation_results.index[0] == data.index[4]
    assert first_row["position"] == 1
    assert first_row["traded_units"] == 1_000


def test_evaluation_starts_with_fresh_capital_and_does_not_carry_training_position():
    registry = make_registry()
    version = make_version()
    instrument_id = uuid4()
    data = make_market_data()

    result = evaluate_strategy(
        registry=registry,
        strategy_version=version,
        instrument_id=instrument_id,
        market_data=data,
        start=data.index[6],
        end_exclusive=data.index[9],
        config=EvaluationConfig(initial_cash=25_000.0),
    )

    first_row = result.simulation_results.iloc[0]

    # A short target is effective at the first test open, but it is a new
    # 1,000-unit short, not a reversal of an inherited long position.
    assert first_row["position"] == -1
    assert abs(first_row["traded_units"]) == 1_000
    assert result.metrics.initial_equity == 25_000.0


